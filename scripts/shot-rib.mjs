import { chromium } from 'playwright-core';
import { readFileSync } from 'fs';
const out = '/tmp/claude-0/-home-claude/6606a69e-0937-5551-a992-fa8245fc1a32/scratchpad';
const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body>' + readFileSync('dist/index.html', 'utf8') + '</body></html>';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
const errs = [];
page.on('pageerror', e => errs.push('PAGEERR ' + e.message));
page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.route('https://cdnjs.cloudflare.com/**', r => r.fulfill({ body: readFileSync('node_modules/three/build/three.min.js'), contentType: 'application/javascript' }));
await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
await page.route('http://app.local/', r => r.fulfill({ body: html, contentType: 'text/html' }));
await page.goto('http://app.local/');
await page.click('[data-tab="prog"]');
await page.selectOption('#sample', 'rib');
await page.click('[data-tab="cond"]');
await page.evaluate(() => { const s = window.machiningSim; s.speed = 3; while (s.mtime < 70) s.step(1 / 60); });
await page.click('#btnPlay');
await page.click('[data-color="wall"]');
await page.evaluate(() => { const v = document.getElementById('exag'); v.value = 400; v.dispatchEvent(new Event('input')); });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/rib.png` });
console.log(await page.textContent('#vW'), await page.textContent('#sW'), errs);
await browser.close();
